// Exercise notification replies with timed recognition only; never open a microphone or deliver a chat. — GPT-6.1 Sol
import Foundation

@main struct NotificationReplyCoreTests {
    static var checks = 0
    static func check(_ condition: @autoclosure () -> Bool, _ name: String) {
        checks += 1
        if !condition() { fatalError(name) }
    }
    static func recognition(_ text: String, times: [Double], stable: Int? = nil, batch: UUID = UUID()) -> NotificationReplyCore.Recognition {
        let tokens = text.lowercased().components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty }
        precondition(tokens.count == times.count)
        return .init(batch: batch, text: text, words: zip(tokens, times).map {
            .init(text: $0.0, start: $0.1, end: $0.1 + 0.1)
        }, stableWords: stable ?? tokens.count)
    }
    static func waiting() -> NotificationReplyCore {
        var core = NotificationReplyCore(at: 0)
        core.audioStarted(); core.audioEnded(at: 10, completed: true, now: 10)
        return core
    }
    static func main() {
        var core = waiting()
        let batch = UUID()
        core.observe(recognition("Reply yes", times: [11, 11.2], batch: batch), now: 13.4)
        check(core.phase == .composing, "late recognition uses spoken time")
        check(core.acceptedCount == 1, "one accepted cue boundary")
        core.tick(now: 20)
        check(core.phase == .composing && core.body == nil, "a pause never submits")
        core.observe(recognition("Reply yes, do that. End reply.", times: [11, 11.2, 20, 20.2, 21, 21.2], stable: 4, batch: batch), now: 21.4)
        check(core.phase == .composing && core.finalizeThrough != nil, "partial End cannot submit")
        core.observe(recognition("Reply yes, do that. End reply.", times: [11, 11.2, 20, 20.2, 21, 21.2], batch: batch), now: 21.7)
        check(core.canDispatch && core.releaseRequested, "only confirmed End requests release")
        check(core.body == "yes, do that.", "preserve body punctuation")
        check(core.acceptedCount == 1, "revisions never accept Reply twice")
        core.queued(); core.queued()
        check(core.phase == .queued && core.body == nil, "drop body after queue reservation")
        core.observe(recognition("Reply duplicate End reply", times: [11, 12, 13, 13.2]), now: 22)
        check(core.phase == .queued, "terminal recognition cannot replay")
        core.delivered(); check(core.phase == .delivered, "arrival is distinct from queue acceptance")

        core = waiting()
        core.observe(recognition("Reply reply to Sunny. End reply", times: [11, 11.2, 11.4, 11.6, 12, 12.2]), now: 12.6)
        check(core.body == "reply to Sunny.", "a genuine leading reply is content")
        core = waiting()
        core.observe(recognition("Reply run that command. End reply.", times: [11, 11.2, 11.4, 11.6, 12, 12.2]), now: 12.6)
        check(core.body == "run that command.", "a complete sentence ending in command doesn't swallow the separate End command")
        core = waiting()
        core.observe(recognition("Reply do not end reply", times: [11, 11.2, 11.4, 11.6, 11.8]), now: 12)
        check(!core.canDispatch, "a negated End mention isn't a send boundary")
        core = waiting()
        core.observe(recognition("Reply End reply", times: [11, 11.5, 11.7]), now: 12)
        check(core.phase == .cancelled && core.reason == "no-reply-content" && !core.canDispatch, "control-only sends nothing")
        core = waiting()
        core.observe(recognition("Reply um End reply", times: [11, 11.2, 11.5, 11.7]), now: 12)
        check(!core.canDispatch, "hesitations alone send nothing")
        core = waiting()
        core.observe(recognition("Reply Okay End reply", times: [11, 11.2, 11.5, 11.7]), now: 12)
        check(core.body == "Okay", "Okay is a meaningful whole answer")

        core = waiting()
        core.observe(recognition("you can reply", times: [10.8, 11, 11.2]), now: 11.5)
        check(core.phase == .waiting, "embedded reply does not activate")
        core.processed(through: 16, now: 16); core.tick(now: 17.6)
        check(core.phase == .cancelled && core.reason == "no-command", "no command releases without sending")
        core = waiting()
        core.observe(recognition("Reply", times: [9.5]), now: 10.5)
        check(core.phase == .waiting, "notification echo before exit is excluded")
        core.observe(recognition("Reply", times: [15.2]), now: 16)
        check(core.phase == .waiting, "spoken outside the five-second window is excluded")
        core = waiting()
        core.observe(recognition("Reply yes", times: [14.5, 14.7]), now: 16)
        check(core.phase == .composing, "speech at four and a half seconds is accepted even when its result is later")
        core = waiting()
        let unstable = UUID()
        core.observe(recognition("Reply", times: [11], stable: 0, batch: unstable), now: 11.3)
        check(core.phase == .waiting && core.finalizeThrough != nil, "volatile activation needs confirmation")
        core.observe(recognition("Really", times: [11], batch: unstable), now: 11.6)
        core.processed(through: 16, now: 16); core.tick(now: 17.6)
        check(core.acceptedCount == 0 && !core.canDispatch, "revised-away activation remains silent")

        core = waiting()
        let pendingStart = UUID()
        core.processed(through: 16, now: 16)
        core.observe(recognition("Reply yes", times: [14.9, 15.2], stable: 0, batch: pendingStart), now: 17.4)
        check(core.confirmingReply && core.phase == .waiting && core.acceptedCount == 0,
              "A genuine timed pending start remains visible without pretending acceptance")
        core.tick(now: 17.6)
        check(core.confirmingReply, "An actual candidate is not discarded by the ordinary no-command watermark")
        core.observe(recognition("Reply yes", times: [14.9, 15.2], batch: pendingStart), now: 17.7)
        check(core.phase == .composing && !core.confirmingReply && core.draftText == "yes",
              "The actual native final retains body words following Reply in the same result")
        core.observe(recognition("continue here", times: [18.1, 18.3]), now: 18.6)
        check(core.draftText == "yes continue here", "The next native batch preserves the reply start after finalizer reset")
        core = waiting()
        core.observe(recognition("Reply", times: [14.9], stable: 0, batch: pendingStart), now: 17.4)
        core.observe(recognition("Really", times: [14.9], batch: pendingStart), now: 17.7)
        check(core.phase == .cancelled && core.reason == "reply-command-unconfirmed" && core.acceptedCount == 0,
              "Changed-away native control never becomes an accepted Reply")
        core = waiting()
        core.observe(recognition("Reply", times: [14.9], stable: 0, batch: pendingStart), now: 17.4)
        core.tick(now: 19)
        check(core.releaseRequested && core.reason == "reply-command-unconfirmed", "A missing real confirmation is finite and truthful")

        core = waiting()
        core.observe(recognition("Reply yes", times: [11, 11.3]), now: 11.6)
        core.observe(recognition("do that", times: [20, 20.2]), now: 20.5)
        let ending = UUID()
        core.observe(recognition("End", times: [21], batch: ending), now: 21.2)
        check(core.phase == .composing, "split End does not submit early")
        core.observe(recognition("End reply", times: [21, 21.3], batch: ending), now: 21.6)
        check(core.body == "yes do that", "multiple recognized utterances preserve the complete reply")
        core = waiting()
        core.observe(recognition("Reply yes", times: [11, 11.3]), now: 11.6)
        core.tick(now: 72)
        check(core.phase == .cancelled && core.reason == "idle-safety-limit" && core.body == nil, "idle limit cancels unsent")
        core = NotificationReplyCore(at: 0, limits: .init(idleSeconds: 180, replySeconds: 10))
        core.audioEnded(at: 10, completed: true, now: 10)
        core.observe(recognition("Reply yes", times: [11, 11.3]), now: 11.6)
        core.tick(now: 22)
        check(core.reason == "reply-limit" && !core.canDispatch, "total limit cancels unsent")
        core = waiting()
        core.audioEnded(at: 10, completed: true, now: 10)
        core.observe(recognition("Reply yes", times: [11, 11.3]), now: 11.6)
        core.cancel("new-user-message")
        core.observe(recognition("End reply", times: [12, 12.2]), now: 12.5)
        check(!core.canDispatch && core.body == nil, "stale/cancelled session cannot be revived")
        core = NotificationReplyCore(at: 0)
        core.audioEnded(at: 10, completed: false, now: 10)
        check(core.phase == .cancelled, "failed announcement never opens a window")
        core = waiting()
        core.observe(.init(batch: UUID(), text: "Reply", words: [], stableWords: 0), now: 11)
        check(core.reason == "recognition-timing-unavailable", "missing event timing fails closed")
        check(NotificationReplyCore.Limits(replySeconds: 999).replySeconds == 180, "maximum remains bounded")
        check(NotificationReplyCore.Limits(replySeconds: .nan).replySeconds == 120, "invalid settings use the default")
        check(NotificationReplyCore.Limits().confirmationSeconds == 1.5 && NotificationReplyCore.Limits().commandDrainSeconds == 2.1,
              "native End allowance leaves the initial no-command timing unchanged")
        check(NotificationReplyCore.Limits(replySeconds: 180).maxHoldSeconds == 194.6, "five seconds flows into the authoritative maximum hold")
        core = NotificationReplyCore(at: 90)
        core.fallbackReady(at: 110)
        check(core.phase == .waiting && core.audioEndedAt == nil && core.opportunityAt == 110, "visual readiness opens one window without fabricated audio")
        core.fallbackReady(at: 114)
        check(core.opportunityAt == 110, "duplicate readiness never extends the opportunity")
        core.observe(recognition("Reply yes End reply", times: [114.5, 114.7, 116, 116.2]), now: 116.5)
        check(core.canDispatch && core.body == "yes", "visual opportunity uses the same complete reply and native End policy")
        core = NotificationReplyCore(at: 90); core.audioStarted(at: 100); core.fallbackReady(at: 105)
        check(core.phase == .announcing && core.opportunityAt == nil, "audio admission excludes visual fallback")
        core = NotificationReplyCore(at: 90); core.cancel("originStale"); core.fallbackReady(at: 100)
        check(core.phase == .cancelled && core.opportunityAt == nil, "fallback cannot revive a cancelled origin")
        for (setup, announcement) in [(70.0, 10.0), (179.0, 40.0)] {
            core = NotificationReplyCore(at: 0, limits: .init(idleSeconds: 180, replySeconds: 120))
            for at in stride(from: 5.0, through: setup, by: 5) { core.ownerSeen(at: at); core.tick(now: at) }
            core.ownerSeen(at: setup); core.tick(now: setup)
            core.audioStarted(at: setup)
            let exit = setup + announcement, reply = exit + 1
            core.tick(now: exit - 0.1)
            core.audioEnded(at: exit, completed: true, now: exit)
            let batch = UUID()
            core.observe(recognition("Reply yes", times: [reply, reply + 0.2], batch: batch), now: reply + 0.4)
            core.tick(now: reply + 119)
            check(core.phase == .composing, "slow setup/announcement retain the full permitted reply")
            core.observe(recognition("Reply yes End reply", times: [reply, reply + 0.2, reply + 119.3, reply + 119.5], batch: batch), now: reply + 120.2)
            check(core.canDispatch, "late native End retains its separate confirmation after a slow setup")
        }
        core = NotificationReplyCore(at: 0); core.audioStarted(at: 0); core.tick(now: 45.1)
        check(core.reason == "announcement-limit", "announcement remains finitely bounded independently of setup and reply")
        core = waiting()
        let oldAnnouncement = UUID()
        core.observe(recognition("Notice Reply yes", times: [9.2, 10.1, 10.3], stable: 0, batch: oldAnnouncement), now: 10.6)
        check(core.confirmingReply, "A genuine in-window Reply can follow completed announcement context")
        core.observe(recognition("Ready Reply yes", times: [9.2, 10.1, 10.3], batch: oldAnnouncement), now: 10.9)
        check(core.phase == .composing && core.draftText == "yes", "An old announcement-word correction does not invalidate unchanged native Reply")
        core = waiting()
        core.observe(recognition("um Reply", times: [10.1, 10.3], stable: 0, batch: oldAnnouncement), now: 10.6)
        core.observe(recognition("say Reply", times: [10.1, 10.3], batch: oldAnnouncement), now: 10.9)
        check(core.acceptedCount == 0 && !core.canDispatch, "Changed in-window command context still prevents activation")
        core = NotificationReplyCore(at: 0, manualFinish: true)
        core.audioEnded(at: 10, completed: true, now: 10)
        core.observe(recognition("Reply yes", times: [11, 11.2]), now: 11.5)
        check(core.ownerLeaseExpiresUptime == 21.5, "Manual acceptance seeds its lease from current owner time")
        for at in stride(from: 12.0, through: 1812.0, by: 1) { core.ownerSeen(at: at); core.tick(now: at) }
        check(core.phase == .composing && core.draftText == "yes", "Thirty minutes of ordinary silence stays composing with its exact owner")
        core.observe(recognition("End reply", times: [1812.1, 1812.3]), now: 1812.6)
        check(core.canDispatch && core.body == "yes" && core.ownerLeaseExpiresUptime == nil, "Explicit End finishes a long manual reply and ends renewal")
        core = NotificationReplyCore(at: 0, manualFinish: true)
        core.audioEnded(at: 10, completed: true, now: 10)
        core.observe(recognition("Reply yes", times: [11, 11.2]), now: 11.5)
        core.ownerSeen(at: 21.5)
        check(core.reason == "owner-lost" && core.releaseRequested, "A late heartbeat cannot renew an expired lease")
        core.ownerSeen(at: 22)
        core.observe(recognition("End reply", times: [22, 22.2]), now: 22.5)
        check(!core.canDispatch && core.body == nil, "A dead owner never revives through speech or another status")
        core = NotificationReplyCore(at: 0, manualFinish: true)
        core.audioEnded(at: 10, completed: true, now: 10)
        core.observe(recognition("Reply yes", times: [11, 11.2]), now: 11.5)
        core.observe(recognition("End reply", times: [22, 22.2]), now: 22.5)
        check(core.reason == "owner-lost" && !core.canDispatch, "Recognition also enforces expiry before a delayed timer fires")
        for text in ["Reply Cancel reply", "Reply yes. Cancel reply"] {
            core = waiting()
            let count = text.split(separator: " ").count
            core.observe(recognition(text, times: (0..<count).map { 11 + Double($0) * 0.2 }), now: 12)
            check(core.reason == "cancel-reply" && core.body == nil && !core.canDispatch, "Confirmed Cancel discards empty or populated capture")
            core.observe(recognition("End reply", times: [13, 13.2]), now: 13.5)
            check(core.phase == .cancelled && !core.canDispatch, "Cancel cannot later send")
        }
        core = waiting()
        core.observe(recognition("Reply yes", times: [11, 11.2]), now: 11.5)
        let cancelling = UUID()
        core.observe(recognition("Cancel reply", times: [12, 12.2], stable: 0, batch: cancelling), now: 12.5)
        check(core.phase == .composing && core.finalizeThrough != nil, "Partial Cancel needs the same native control proof")
        core.observe(recognition("Cancel reply background", times: [12, 12.2, 12.5], batch: cancelling), now: 12.8)
        check(core.reason == "cancel-reply" && !core.canDispatch, "Unchanged canonical Cancel ends at its timed native-final boundary")
        core = waiting()
        core.observe(recognition("Reply yes", times: [11, 11.2]), now: 11.5)
        core.observe(recognition("Cancel reply", times: [12, 12.2], stable: 0, batch: cancelling), now: 12.5)
        core.observe(recognition("Camera replied", times: [12, 12.2], batch: cancelling), now: 12.8)
        check(core.phase == .composing && !core.canDispatch, "Changed-away Cancel is body, never a command")
        core = waiting()
        core.observe(recognition("Reply do not cancel reply", times: [11, 11.2, 11.4, 11.6, 11.8]), now: 12)
        check(core.phase == .composing && !core.releaseRequested, "Negated Cancel remains body")
        core = waiting()
        core.observe(recognition("Reply", times: [11], stable: 0), now: 11.2)
        core.observe(recognition("Cancel reply", times: [12, 12.2]), now: 12.5)
        check(core.reason == "cancel-reply" && core.acceptedCount == 0, "A genuine native Cancel also discards the pending initial Reply")
        print("Notification reply core: \(checks) checks passed")
    }
}
